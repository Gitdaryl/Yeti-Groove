#!/usr/bin/env node
// Refreshes the Field Office page from every client's feature list.
//
//   node tools/field-office-sync.mjs                 # sources from env or ~/.config/field-office/sources.txt
//   node tools/field-office-sync.mjs path-or-url ... # explicit sources (a local file works too)
//
// Writes media/field-office/snapshot.js (the API's fallback) and prerenders the
// marked blocks in field-office.html, so crawlers and no-script visitors see
// the same catalog the live page shows. The page still refreshes itself from
// /api/field-office-features; run this before a push so the two agree.
//
// The snapshot is published (this repo is public), so a client with
// showName:false is written with its name removed.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const { merge, validManifest, renderGrid, renderCustom, renderChips, renderFeed, renderStats } =
  await import(join(ROOT, 'media/field-office/catalog.js'));
const { sceneFor } = await import(join(ROOT, 'media/field-office/anims.js'));

function sources() {
  const args = process.argv.slice(2);
  if (args.length) return args;
  if (process.env.FIELD_OFFICE_SOURCES) return process.env.FIELD_OFFICE_SOURCES.split(/[\s,]+/).filter(Boolean);
  const f = join(homedir(), '.config/field-office/sources.txt');
  if (existsSync(f)) return readFileSync(f, 'utf8').split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
  return [];
}

async function load(src) {
  if (/^https?:\/\//.test(src)) {
    const r = await fetch(src, { signal: AbortSignal.timeout(8000) });
    const type = r.headers.get('content-type') || '';
    if (!r.ok || !type.includes('json')) throw new Error(`${src}: ${r.status} ${type}`);
    return r.json();
  }
  return JSON.parse(readFileSync(src.replace(/^~/, homedir()), 'utf8'));
}

const key = (name) => createHash('sha256').update(String(name || '')).digest('hex').slice(0, 12);

const list = sources();
if (!list.length) {
  console.error('No sources. Pass paths/URLs, set FIELD_OFFICE_SOURCES, or list them in ~/.config/field-office/sources.txt');
  process.exit(1);
}

const manifests = [];
for (const s of list) {
  try {
    const m = await load(s);
    if (!validManifest(m)) throw new Error(`${s}: not a schema 1 manifest`);
    const k = key(m.client.name);
    if (!m.client.showName) m.client = { ...m.client, name: '' };
    manifests.push({ key: k, ...m });
    console.log(`ok  ${m.client.showName ? m.client.name : '(unnamed client)'}: ${m.features.length} features, updated ${m.updated}`);
  } catch (e) {
    console.error(`FAIL ${e.message}`);
    process.exitCode = 1;
  }
}
if (!manifests.length) process.exit(1);

const snapFile = join(ROOT, 'media/field-office/snapshot.js');
writeFileSync(snapFile,
  '// Generated by tools/field-office-sync.mjs. Do not edit by hand.\n' +
  '// Fallback for /api/field-office-features when a client app cannot be reached.\n' +
  `export default ${JSON.stringify({ fetchedAt: new Date().toISOString(), manifests }, null, 2)};\n`);

const data = merge(manifests);
const now = Date.now();
const stats = renderStats(data, now);
const blocks = {
  GRID: renderGrid(data, now),
  CUSTOM: renderCustom(data, now),
  CHIPS: renderChips(data),
  FEED: renderFeed(data),
};

const htmlFile = join(ROOT, 'field-office.html');
let html = readFileSync(htmlFile, 'utf8');
for (const [name, body] of Object.entries(blocks)) {
  const re = new RegExp(`(<!-- FO:${name}:START -->)[\\s\\S]*?(<!-- FO:${name}:END -->)`);
  if (!re.test(html)) { console.error(`field-office.html is missing the FO:${name} markers`); process.exit(1); }
  // A function, not a string: scene text like "$184.20" would otherwise read as a $1 backreference.
  html = html.replace(re, (_, open, close) => `${open}${body}${close}`);
}
// Story scenes are fixed, but they come from the same scene library.
html = html.replace(/(<div class="fo-anim (?:scene|loop)" data-anim="([\w-]+)"[^>]*>)[\s\S]*?(<\/div><!-- \/scene -->)/g,
  (_, open, anim, close) => {
    const sc = sceneFor(anim);
    return `${open.replace(/style="[^"]*"/, `style="--p:${sc.still}"`)}${sc.svg}${close}`;
  });
for (const [k, v] of Object.entries(stats)) {
  html = html.replace(new RegExp(`(<span data-stat="${k}">)[^<]*(</span>)`, 'g'), (_, open, close) => `${open}${v}${close}`);
}
writeFileSync(htmlFile, html);
console.log(`wrote snapshot (${manifests.length} client(s)) and field-office.html: ${data.count} features, ${stats.fresh} new, updated ${stats.updated}`);
